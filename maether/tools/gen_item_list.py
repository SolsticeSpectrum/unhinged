#!/usr/bin/env python3
"""Regenerates tools/items.txt (names that need pack item definitions) from the Java registries."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root/"src/main/java/com/kestrel/maether/item/AetherItems.java").read_text() + (root/"src/main/java/com/kestrel/maether/acc/Accessories.java").read_text()
names = set(re.findall(r'item\("([a-z_]+)"', src)) | set(re.findall(r'acc\("([a-z_]+)"', src))
for arr in re.findall(r'new String\[\]\{([^}]*)\}', src): names |= set(re.findall(r'"([a-z_]+)"', arr))
for t in ("skyroot", "holystone", "zanite", "gravitite"):
    for k in ("pickaxe", "axe", "shovel", "sword", "hoe"): names.add(f"{t}_{k}")
for s in ("zanite", "gravitite", "valkyrie", "neptune", "phoenix", "obsidian"):
    for k in ("helmet", "chestplate", "leggings", "boots"): names.add(f"{s}_{k}")
names.add("sentry_boots")
ent = (root/"src/main/java/com/kestrel/maether/entity/AetherEntities.java").read_text()
for n in re.findall(r'mob\("([a-z_]+)"', ent): names.add(n + "_spawn_egg")
names |= {"blue_moa_egg", "white_moa_egg", "black_moa_egg"}
for g in ("leather","chainmail","iron","golden","diamond","netherite","zanite","gravitite","valkyrie","neptune","phoenix","obsidian"): names.add(f"{g}_gloves")
names -= {"leather_gloves"} if False else set()
(root/"tools/items.txt").write_text("# generated by gen_item_list.py\n" + "\n".join(sorted(names)) + "\n")
print(len(names))
