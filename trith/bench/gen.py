#!/usr/bin/env python3
"""Generate the n-body benchmark in Trith (logical order) and in C.

Both programs perform exactly the same floating-point operations in the same
order, so their printed results must match bit for bit. Real literals in Trith
are ternary fractions, so initial values are rationals n/3^k, written the same
way in C. Run: python3 trith/bench/gen.py, then plough nbody.logical.trh.
"""
from fractions import Fraction as F

STEPS = 1_000_000
DT = F(1, 81)
# body: x y z vx vy vz m
BODIES = [
    [F(0), F(0), F(0), F(0), F(0), F(0), F(9)],
    [F(3), F(0), F(0), F(0), F(5, 3), F(0), F(1, 27)],
    [F(-6), F(1, 3), F(0), F(0), F(-4, 3), F(1, 9), F(1, 9)],
    [F(0), F(10), F(-1, 3), F(-1), F(0), F(0), F(1, 3)],
    [F(0), F(-14), F(2, 3), F(7, 9), F(0), F(-1, 27), F(2, 9)],
]


def bt(n):
    """balanced ternary digits of integer n, least significant first"""
    d = []
    while n != 0:
        r = n % 3
        if r == 0:
            d.append(0); n //= 3
        elif r == 1:
            d.append(1); n = (n - 1) // 3
        else:
            d.append(-1); n = (n + 1) // 3
    return d


SYM = {-1: '▽', 0: '○', 1: '△'}


def int_lit(n):
    return ''.join(SYM[x] for x in bt(n)) or '○'


def real_lit(q):
    k = 0
    while q.denominator != 3 ** k:
        k += 1
        if k > 40:
            raise ValueError(q)
    digits = bt(q.numerator * (3 ** k) // q.denominator)
    digits += [0] * (k + 1 - len(digits)) if len(digits) < k + 1 else []
    ip = digits[k:] or [0]
    fp = [digits[i] for i in range(k - 1, -1, -1)] or [0]
    return ''.join(SYM[x] for x in ip) + '⁝' + ''.join(SYM[x] for x in fp)


def c_real(q):
    return f'({q.numerator}.0 / {q.denominator}.0)'


class Fn:
    """straight-line Trith over one array on the stack, values in moments"""

    def __init__(self):
        self.lines = []
        self.moments = []

    def get(self, name, k):
        self.lines.append(f'⟗ {int_lit(k)} ᚷ ⧖')
        self.moments.append(name)

    def ref(self, name):
        return f'⧗{sup(len(self.moments) - 1 - self.moments.index(name))}'

    def bind(self, name, code):
        self.lines.append(f'{code} ⧖')
        self.moments.append(name)

    def set(self, k, code):
        self.lines.append(f'{int_lit(k)} {code} ᛊ')


def sup(n):
    return ''.join('⁰¹²³⁴⁵⁶⁷⁸⁹'[int(c)] for c in str(n))


def gen():
    fn = Fn()
    dt = real_lit(DT)
    c = []
    names = 0
    for i in range(5):
        for j in range(i + 1, 5):
            p = f'p{i}{j}_'
            for f, axis in enumerate('xyz'):
                fn.get(p + axis + 'i', 7 * i + f)
                fn.get(p + axis + 'j', 7 * j + f)
            for axis in 'xyz':
                fn.bind(p + 'd' + axis, f'{fn.ref(p + axis + "i")} {fn.ref(p + axis + "j")} ⊟')
            dx, dy, dz = (fn.ref(p + 'd' + a) for a in 'xyz')
            fn.bind(p + 'd2', f'{dx} {dx} ⊠ {fn.ref(p + "dy")} {fn.ref(p + "dy")} ⊠ ⊞')
            fn.bind(p + 'd2b', f'{fn.ref(p + "d2")} {fn.ref(p + "dz")} {fn.ref(p + "dz")} ⊠ ⊞')
            fn.bind(p + 'mag', f'{dt} {fn.ref(p + "d2b")} {fn.ref(p + "d2b")} ᛋ ⊠ ⊘ ⁇ ⦃ ⦄ ⦃ ○⁝○ ⦄')
            fn.get(p + 'mi', 7 * i + 6)
            fn.get(p + 'mj', 7 * j + 6)
            for f, axis in enumerate('xyz'):
                fn.get(p + 'v' + axis + 'i', 7 * i + 3 + f)
                d = fn.ref(p + 'd' + axis)
                fn.set(7 * i + 3 + f, f'{fn.ref(p + "v" + axis + "i")} {d} {fn.ref(p + "mj")} ⊠ {fn.ref(p + "mag")} ⊠ ⊟')
            for f, axis in enumerate('xyz'):
                fn.get(p + 'v' + axis + 'j', 7 * j + 3 + f)
                d = fn.ref(p + 'd' + axis)
                fn.set(7 * j + 3 + f, f'{fn.ref(p + "v" + axis + "j")} {d} {fn.ref(p + "mi")} ⊠ {fn.ref(p + "mag")} ⊠ ⊞')
            c.append(f'    pair(a, {i}, {j});')
    for b in range(5):
        for f in range(3):
            fn.get(f'pos{b}{f}', 7 * b + f)
            fn.get(f'vel{b}{f}', 7 * b + 3 + f)
            fn.set(7 * b + f, f'{fn.ref(f"pos{b}{f}")} {dt} {fn.ref(f"vel{b}{f}")} ⊠ ⊞')
    body = '\n'.join('  ' + l for l in fn.lines)
    init = ' '.join(real_lit(v) for b in BODIES for v in b)
    steps = int_lit(STEPS)
    trith = f'''⍝ benchmark: 5-body gravity, {STEPS} steps (generated by trith/bench/gen.py)
⍝ the state is one array of 35 reals: body b, field f at 7b+f (x y z vx vy vz m)
⎔ »trqs« ⟨ℝ ⊸ ℝ⟩ ᛋ ⸫
⍝ ᚷ reads field k; ᛊ writes field k (positions are centre-based, so k − 17)
⦃ {int_lit(-17)} ⊞ ⌖̱ ⁇ ⦃ ⦄ ⦃ ○⁝○ ⦄ ⦄ ⟨⟗⟦ℝ⟧ ℤ ⊸ ℝ⟩ ᚷ ⸫
⦃ ⧖ ⧖ ⟖ ⧗⁰ {int_lit(-17)} ⊞ ⧗¹ ⍈̱ ⁇ ⦃ ⦄ ⦃ ⦄ ⦄ ⟨⟦ℝ⟧ ℤ ℝ ⊸ ⟦ℝ⟧⟩ ᛊ ⸫
⍝ one time step
⦃
{body}
⦄ ⟨⟦ℝ⟧ ⊸ ⟦ℝ⟧⟩ ᚨ ⸫
⦃
  ⟦ {init} ⟧
  ○ ⥀ ⦃ ⧖ ᚨ ⧗⁰ △ ⊞ {steps} ⍿¹ ≶ ⦄ ⌁
  ⟗ ○ ᚷ ⎙ ⟗ △ ᚷ ⎙ ⟗ {int_lit(7)} ᚷ ⎙ ⟗ {int_lit(8)} ᚷ ⎙ ⟗ {int_lit(29)} ᚷ ⎙
  ⌁̵
⦄ ⟨⊸⟩ ᛟ ⸫
'''
    inits = ',\n    '.join(', '.join(c_real(v) for v in b) for b in BODIES)
    cprog = f'''/* benchmark: 5-body gravity (generated by trith/bench/gen.py) */
#include <math.h>
#include <stdio.h>

#define DT {c_real(DT)}

static void pair(double *a, int i, int j) {{
    double dx = a[7 * i] - a[7 * j];
    double dy = a[7 * i + 1] - a[7 * j + 1];
    double dz = a[7 * i + 2] - a[7 * j + 2];
    double d2 = dx * dx + dy * dy;
    double d2b = d2 + dz * dz;
    double mag = DT / (d2b * sqrt(d2b));
    double mi = a[7 * i + 6], mj = a[7 * j + 6];
    a[7 * i + 3] = a[7 * i + 3] - dx * mj * mag;
    a[7 * i + 4] = a[7 * i + 4] - dy * mj * mag;
    a[7 * i + 5] = a[7 * i + 5] - dz * mj * mag;
    a[7 * j + 3] = a[7 * j + 3] + dx * mi * mag;
    a[7 * j + 4] = a[7 * j + 4] + dy * mi * mag;
    a[7 * j + 5] = a[7 * j + 5] + dz * mi * mag;
}}

static void advance(double *a) {{
{chr(10).join(c)}
    for (int b = 0; b < 5; b++) {{
        for (int f = 0; f < 3; f++) {{
            a[7 * b + f] = a[7 * b + f] + DT * a[7 * b + 3 + f];
        }}
    }}
}}

int main(void) {{
    double a[35] = {{
    {inits}
    }};
    for (long n = 0; n < {STEPS}; n++) {{
        advance(a);
    }}
    printf("%.15g\\n%.15g\\n%.15g\\n%.15g\\n%.15g\\n", a[0], a[1], a[7], a[8], a[29]);
    return 0;
}}
'''
    return trith, cprog


LIFE_W = 512
LIFE_GENS = 1000


def gen_life():
    """Game of Life on a 512x512 torus; both programs use the same LCG seed."""
    n = LIFE_W * LIFE_W
    # element 0 is the array literal's seed cell, so cell i sits at position i + 1
    off = int_lit(-(n // 2) + 1)
    mask = int_lit(LIFE_W - 1)
    shift = int_lit(9)
    # ᚾ: live neighbours of cell idx in shadow sh
    reads = []
    first = True
    for dr in (-1, 0, 1):
        for dc in (-1, 0, 1):
            if dr == 0 and dc == 0:
                continue
            # moments: ⧗⁰ c, ⧗¹ r, ⧗² sh (a shadow, so read as ⧗̱²), ⧗³ idx
            rr = f'⧗¹ {int_lit(dr)} ⊞ {mask} ⋒' if dr else f'⧗¹'
            cc = f'⧗⁰ {int_lit(dc)} ⊞ {mask} ⋒' if dc else f'⧗⁰'
            reads.append(f'⧗̱² {rr} {shift} ≪ {cc} ⋓ ᚷ' + ('' if first else ' ⊞'))
            first = False
    count = '\n'.join('  ' + r for r in reads)
    trith = f'''⍝ benchmark: Game of Life, {LIFE_W}x{LIFE_W} torus, {LIFE_GENS} generations (generated by trith/bench/gen.py)
⍝ ᚷ reads cell i of a grid (centre-based positions; the seed cell comes first); missing cells are dead
⦃ {off} ⊞ ⌖̱ ⁇ ⦃ ⦄ ⦃ ○ ⦄ ⦄ ⟨⟗⟦ℤ⟧ ℤ ⊸ ℤ⟩ ᚷ ⸫
⍝ ᚾ counts the live neighbours of cell idx
⦃
  ⧖ ⧖ ⧗¹ {shift} ≫ ⧖ ⧗² {mask} ⋒ ⧖
{count}
⦄ ⟨⟗⟦ℤ⟧ ℤ ⊸ ℤ⟩ ᚾ ⸫
⍝ ᛚ: the next state from [alive n]: 3 neighbours live, 2 keep the cell, else die
⦃
  ⧖ ⧖ ⧗⁰ ⧗¹ ⧗¹ ○△ ≶ ⋔
    ⦃ ⌁ ⌁ △ ⦄
    ⦃ ⌁ ⌁ ○ ⦄
    ⦃ ▽△ ≶ ⋔ ⦃ ⦄ ⦃ ⌁ ○ ⦄ ⦃ ⌁ ○ ⦄ ⦄
⦄ ⟨ℤ ℤ ⊸ ℤ⟩ ᛚ ⸫
⍝ ᛞ writes the next generation of old (a shadow) into new.
⍝ The prayer states that both grids hold all {n + 1} cells, which lets the
⍝ optimiser drop every bounds check (§12)
⦃
  ⍤¹ ⦃ ⍴̱ {int_lit(n + 1)} ≶ ⋔ ⦃ ⊕ ⦄ ⦃ ⊖ ⦄ ⁼ ⦄
  ⍤² ⦃ ⌁̱ ⍴̱ {int_lit(n + 1)} ≶ ⋔ ⦃ ⊕ ⦄ ⦃ ⊖ ⦄ ⁼ ⦄
  ○ ⍿² ⥀ ⦃
    ⧖ ⧖
    ⟖ ⧗⁰ {off} ⊞ ⧗̱¹ ⧗⁰ ᚷ ⧗̱¹ ⧗⁰ ᚾ ᛚ ⍈̱ ⁇ ⦃ ⦄ ⦃ ⦄
    ⧗⁰ △ ⊞ ⧗̱¹ {int_lit(n)} ⍿² ≶
  ⦄
  ⌁̱ ⌁ ⧖ ⌁̱ ⧗̵⁰
⦄ ⟨⟗⟦ℤ⟧ ⟦ℤ⟧ ⊸ ⟦ℤ⟧⟩ ᛞ ⸫
⦃
  ⍝ two grids from a linear congruential generator; the second starts dead
  ⟦ ○ ⟧ ⟦ ○ ⟧ ○ {int_lit(42)} ⥀ ⦃
    ⧖ ⧖ ⧗¹ {int_lit(1103515245)} ⊠ {int_lit(12345)} ⊞ {int_lit(0x7fffffff)} ⋒ ⧖
    ⍿¹ ⧗⁰ {int_lit(16)} ≫ △ ⋒ ⍆̵ ⍿¹ ○ ⍆̵
    ⧗¹ △ ⊞ ⧗⁰ {int_lit(n)} ⍿² ≶
  ⦄
  ⌁ ⌁
  ○ ⥀ ⦃
    ⧖ ⍿¹ ⟗ ⍿² ᛞ ⍿¹
    ⧗⁰ △ ⊞ {int_lit(LIFE_GENS)} ⍿¹ ≶
  ⦄
  ⌁
  ⍝ count the live cells of the newest generation
  ⍿¹ ○ ○ ⥀ ⦃ ⧖ ⧖ ⟗ ⧗⁰ ᚷ ⧗¹ ⊞ ⧖ ⧗¹ △ ⊞ ⧗⁰ {int_lit(n)} ⍿² ≶ ⦄
  ⎙ ⌁ ⌁̵ ⌁̵
⦄ ⟨⊸⟩ ᛟ ⸫
'''
    cprog = f'''/* benchmark: Game of Life (generated by trith/bench/gen.py) */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

#define W {LIFE_W}
#define N (W * W)

static int64_t cell(const int64_t *g, int64_t i) {{ return g[i]; }}

static int64_t count(const int64_t *g, int64_t idx) {{
    int64_t r = idx >> 9, c = idx & (W - 1), n = 0;
    for (int64_t dr = -1; dr <= 1; dr++) {{
        for (int64_t dc = -1; dc <= 1; dc++) {{
            if (dr == 0 && dc == 0) continue;
            n += cell(g, (((r + dr) & (W - 1)) << 9) | ((c + dc) & (W - 1)));
        }}
    }}
    return n;
}}

static int64_t next(int64_t alive, int64_t n) {{
    if (n == 3) return 1;
    if (n > 3) return 0;
    return n == 2 ? alive : 0;
}}

int main(void) {{
    int64_t *a = calloc(N + 1, sizeof *a), *b = calloc(N + 1, sizeof *b);
    int64_t x = 42;
    for (int64_t i = 0; i < N; i++) {{
        x = (x * 1103515245 + 12345) & 0x7fffffff;
        a[i + 1] = (x >> 16) & 1;
    }}
    /* index 0 holds the seed cell of the Trith version's array literal */
    int64_t *old = a + 1, *new = b + 1;
    for (int g = 0; g < {LIFE_GENS}; g++) {{
        for (int64_t i = 0; i < N; i++) new[i] = next(old[i], count(old, i));
        int64_t *t = old; old = new; new = t;
    }}
    int64_t live = 0;
    for (int64_t i = 0; i < N; i++) live += old[i];
    printf("%lld\\n", (long long)live);
    free(a);
    free(b);
    return 0;
}}
'''
    return trith, cprog


if __name__ == '__main__':
    import os
    here = os.path.dirname(os.path.abspath(__file__))
    t, c = gen()
    with open(os.path.join(here, 'nbody.logical.trh'), 'w') as f:
        f.write(t)
    with open(os.path.join(here, 'nbody.c'), 'w') as f:
        f.write(c)
    t, c = gen_life()
    with open(os.path.join(here, 'life.logical.trh'), 'w') as f:
        f.write(t)
    with open(os.path.join(here, 'life.c'), 'w') as f:
        f.write(c)
